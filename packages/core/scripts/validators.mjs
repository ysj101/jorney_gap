import { readFileSync, writeFileSync } from "node:fs";
import { Ajv } from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import {
  configSchema,
  journeySchema,
  relayConfigSchema,
} from "../dist/config-schema.js";

const ajv = new Ajv({
  allErrors: true,
  useDefaults: true,
  code: { source: true, lines: true },
});
ajv.addSchema(configSchema, "web");
ajv.addSchema(relayConfigSchema, "relay");
// Analyze takes an already normalized definition and must not mutate it.
const normalizedJourney = structuredClone(journeySchema);
delete normalizedJourney.properties.timeoutMinutes.default;
ajv.addSchema(normalizedJourney, "journey");
const content = `// Generated by pnpm validators:generate; do not edit.\n${standalone(ajv, { validateWeb: "web", validateRelay: "relay", validateJourney: "journey" })}\n`;
const path = new URL("../src/generated/validators.cjs", import.meta.url);
if (process.argv.includes("--write")) writeFileSync(path, content);
else if (readFileSync(path, "utf8") !== content)
  throw new Error(
    "Stale compiled validators; run pnpm validators:generate and rebuild",
  );
