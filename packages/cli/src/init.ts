import {
  closeSync,
  existsSync,
  openSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { type JourneyGapConfig, validateConfig } from "@journeygap/core";
import { CliError } from "./config.js";
import {
  canonicalRoot,
  dependencies,
  detectEntry,
  entryPatch,
  hash,
  INSTALL_FILE,
  type InstallState,
  LOCK_FILES,
  locked,
  managedPaths,
  manager,
  type ProjectRuntime,
  packageJson,
  readInstall,
  restore,
  runtime,
  SDK_VERSION,
  safePath,
  snapshot,
  textFile,
  verifyManaged,
} from "./project.js";

export type InitOptions = { endpoint?: string; approveConfigChange?: string };
export type InitResult = {
  status: "installed" | "unchanged" | "config-updated";
  files: string[];
};
const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
function sdkVersion(root: string): void {
  let version: unknown;
  try {
    version = JSON.parse(
      textFile(join(root, "node_modules/@journeygap/web/package.json"), 262144),
    ).version;
  } catch {
    throw new CliError(
      "SDK installation is incomplete; reconcile dependencies before retrying",
    );
  }
  if (
    typeof version !== "string" ||
    !/^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/.test(version) ||
    version.split(".").slice(0, 2).join(".") !==
      SDK_VERSION.split(".").slice(0, 2).join(".")
  )
    throw new CliError(
      "The existing SDK version is incompatible with this CLI; update it deliberately rather than forcing an overwrite",
    );
}
function configuration(name: unknown, endpoint?: string): JourneyGapConfig {
  let serviceName =
    typeof name === "string"
      ? name
          .toLowerCase()
          .replace(/^@/, "")
          .replace(/[^a-z0-9._-]/g, "-")
      : "sample-web";
  if (!/^[a-z]/.test(serviceName)) serviceName = `app-${serviceName}`;
  serviceName = serviceName.slice(0, 64);
  const steps = [
    { id: "started" },
    { id: "reviewed" },
    { id: "completed", terminal: true },
  ];
  const result = validateConfig({
    $comment:
      "Generated by JourneyGap CLI. Change journey definitions deliberately; uninstall preserves edited files.",
    schemaVersion: 1,
    enabled: endpoint !== undefined,
    serviceName,
    otlpTracesEndpoint: endpoint ?? "https://ingest.example.invalid/v1/traces",
    consent: { mode: "opt-in", ui: "compact" },
    routes: [
      { id: "home", pattern: "/" },
      { id: "first-task", pattern: "/first-task" },
      { id: "second-task", pattern: "/second-task" },
    ],
    journeys: [
      { id: "first-task", steps, timeoutMinutes: 30 },
      { id: "second-task", steps, timeoutMinutes: 30 },
    ],
  });
  if (!result.valid)
    throw new CliError(
      "Invalid public OTLP endpoint or generated configuration; no changes made",
    );
  return result.value;
}

function updateConfiguration(
  root: string,
  state: InstallState,
  options: InitOptions,
): InitResult {
  verifyManaged(root, state);
  if (options.endpoint === undefined) return { status: "unchanged", files: [] };
  const path = safePath(root, "journeygap.config.json");
  const before = textFile(path);
  const current = validateConfig(JSON.parse(before));
  if (!current.valid)
    throw new CliError(
      "Installed configuration is invalid; inspect it manually",
    );
  const proposed = validateConfig({
    ...current.value,
    enabled: true,
    otlpTracesEndpoint: options.endpoint,
  });
  if (!proposed.valid)
    throw new CliError("Invalid public OTLP endpoint; no changes made");
  if (
    current.value.enabled &&
    current.value.otlpTracesEndpoint === options.endpoint
  )
    return { status: "unchanged", files: [] };
  const content = json(proposed.value);
  const approval = hash(before + content).slice(0, 24);
  if (options.approveConfigChange !== approval)
    throw new CliError(
      `Configuration diff (no changes made):\n- enabled: ${current.value.enabled}; endpoint: ${current.value.otlpTracesEndpoint}\n+ enabled: true; endpoint: ${proposed.value.otlpTracesEndpoint}\nReview this diff, then rerun init with the same --endpoint and --approve-config-change ${approval}`,
    );
  const files = snapshot(root, ["journeygap.config.json", INSTALL_FILE]);
  try {
    writeFileSync(path, content);
    state.files["journeygap.config.json"] = hash(content);
    writeFileSync(safePath(root, INSTALL_FILE), json(state));
  } catch {
    restore(files);
    throw new CliError("Configuration update failed; original files restored");
  }
  return {
    status: "config-updated",
    files: ["journeygap.config.json", INSTALL_FILE],
  };
}

export async function initProject(
  cwd: string,
  options: InitOptions = {},
  tools: ProjectRuntime = runtime,
): Promise<InitResult> {
  const root = canonicalRoot(cwd);
  const pkg = packageJson(root);
  // Validate before taking a lock or invoking a package manager.
  const config = configuration(pkg.name, options.endpoint);
  const existing = readInstall(root);
  if (existing)
    return locked(root, async () =>
      updateConfiguration(root, existing, options),
    );
  if (options.approveConfigChange !== undefined)
    throw new CliError(
      "Config approval applies only to a reviewed existing installation",
    );
  const pm = manager(root, pkg);
  const entry = detectEntry(root, pkg);
  const files = managedPaths(entry);
  for (const name of files)
    if (existsSync(safePath(root, name)))
      throw new CliError(
        `Existing ${name} will not be overwritten; integrate it manually`,
      );
  const source = textFile(safePath(root, entry));
  const patch = entryPatch(source, entry);
  const addedDependency = !dependencies(pkg)["@journeygap/web"];
  const installed = existsSync(
    join(root, "node_modules/@journeygap/web/package.json"),
  );
  if (installed && !addedDependency) sdkVersion(root);
  const needsInstall = addedDependency || !installed;
  return locked(root, async () => {
    const originals = snapshot(root, [
      "package.json",
      ...LOCK_FILES,
      entry,
      ...files,
      INSTALL_FILE,
    ]);
    const rawPath = relative(
      dirname(safePath(root, files[1] ?? "")),
      safePath(root, "journeygap.config.json"),
    )
      .split(sep)
      .join("/");
    const modulePath = rawPath.startsWith(".") ? rawPath : `./${rawPath}`;
    const generated: Record<string, string> = {
      "journeygap.config.json": json(config),
      [files[1] ?? ""]:
        `// Generated by JourneyGap CLI. No application state is read.\n/// <reference path="./journeygap-env.d.ts" />\nimport rawConfig from ${JSON.stringify(`${modulePath}?raw`)};\nimport type { JourneyGapConfig } from "@journeygap/web";\nvoid import("@journeygap/web").then(({ initJourneyGap }) => {\n  initJourneyGap(JSON.parse(rawConfig) as JourneyGapConfig);\n}).catch(() => { /* Telemetry load/config failures never block the host. */ });\n`,
      [files[2] ?? ""]:
        '// Generated by JourneyGap CLI for Vite raw JSON imports.\ndeclare module "*.json?raw" { const content: string; export default content; }\n',
    };
    const created = new Set<string>();
    let entryWritten = false;
    const rollback = () => {
      const restoreFiles = originals.filter((file) => {
        if (file.path === safePath(root, entry)) return false;
        const name = relative(root, file.path).split(sep).join("/");
        if (name in generated && file.data === null && existsSync(file.path))
          return (
            created.has(name) &&
            hash(readFileSync(file.path)) === hash(generated[name] ?? "")
          );
        if (name === INSTALL_FILE && file.data === null)
          return created.has(name);
        return name === "package.json" || LOCK_FILES.includes(name)
          ? needsInstall
          : true;
      });
      restore(restoreFiles);
      const current = textFile(safePath(root, entry));
      if (current === patch.text && entryWritten)
        writeFileSync(safePath(root, entry), source);
      else if (entryWritten && current.split(patch.block).length === 2)
        writeFileSync(safePath(root, entry), current.replace(patch.block, ""));
    };
    const createFile = (name: string, content: string, mode = 0o644) => {
      const fd = openSync(safePath(root, name), "wx", mode);
      created.add(name);
      try {
        writeFileSync(fd, content);
      } finally {
        closeSync(fd);
      }
    };
    try {
      if (addedDependency)
        await tools.command(
          pm,
          pm === "npm"
            ? [
                "install",
                "--save-exact",
                "--ignore-scripts",
                "--no-audit",
                "--no-fund",
                `@journeygap/web@${SDK_VERSION}`,
              ]
            : [
                "add",
                "--save-exact",
                "--ignore-scripts",
                `@journeygap/web@${SDK_VERSION}`,
              ],
          root,
        );
      if (!addedDependency && needsInstall)
        await tools.command(
          pm,
          pm === "npm"
            ? ["install", "--ignore-scripts", "--no-audit", "--no-fund"]
            : ["install", "--ignore-scripts", "--no-frozen-lockfile"],
          root,
        );
      sdkVersion(root);
      for (const [name, content] of Object.entries(generated))
        createFile(name, content);
      // Preserve every byte outside the AST-selected managed import region.
      if (textFile(safePath(root, entry)) !== source)
        throw new CliError("Entry changed during installation");
      writeFileSync(safePath(root, entry), patch.text);
      entryWritten = true;
      await tools.typecheck(root);
      const state: InstallState = {
        schemaVersion: 1,
        generatedBy: `@journeygap/cli@${SDK_VERSION}`,
        entry,
        managedBlock: patch.block,
        entryBeforeHash: hash(source),
        packageBeforeHash: hash(
          originals.find((file) => file.path === safePath(root, "package.json"))
            ?.data ?? "",
        ),
        lockBeforeHashes: Object.fromEntries(
          LOCK_FILES.map((name) => {
            const original = originals.find(
              (file) => file.path === safePath(root, name),
            );
            return [name, original?.data ? hash(original.data) : null];
          }),
        ),
        manager: pm,
        addedDependency,
        dependencyName: "@journeygap/web",
        addedDependencyVersion: addedDependency ? SDK_VERSION : null,
        files: Object.fromEntries(
          Object.entries(generated).map(([name, content]) => [
            name,
            hash(content),
          ]),
        ),
      };
      createFile(INSTALL_FILE, json(state), 0o600);
      return {
        status: "installed",
        files: [
          entry,
          ...files,
          INSTALL_FILE,
          ...(addedDependency ? ["package.json"] : []),
        ],
      };
    } catch {
      try {
        rollback();
      } catch {
        throw new CliError(
          "Installation failed and rollback could not finish. Inspect project file permissions and git diff; no git history was changed",
        );
      }
      if (needsInstall) {
        try {
          await tools.command(
            pm,
            pm === "npm"
              ? ["prune", "--ignore-scripts", "--no-audit", "--no-fund"]
              : [
                  "install",
                  "--offline",
                  "--ignore-scripts",
                  "--no-frozen-lockfile",
                ],
            root,
          );
        } catch {
          /* Restore tracked files even if cache cleanup is unavailable. */
        }
        rollback();
      }
      throw new CliError(
        "Dependency installation or typecheck failed; project files were restored. Run the package manager to reconcile any unused node_modules cache",
      );
    }
  });
}
